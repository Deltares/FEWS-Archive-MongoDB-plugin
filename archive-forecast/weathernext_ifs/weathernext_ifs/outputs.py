@log
def write(model_forecast, output_folder, output_file, levels, fields, corners, downscale, downscale_method, t0):
	model_forecast = _trim(model_forecast, levels, fields)
	model_forecast = _clip(model_forecast, corners)
	model_forecast = _resample(model_forecast, downscale, downscale_method)
	model_forecast = _zero_negative_precipitation(model_forecast)
	model_forecast = _metadata(model_forecast)
	model_forecast = _update_datetime(model_forecast)
	single_level, pressure_levels = _split(model_forecast)

	os.makedirs(output_folder, exist_ok=True)
	output_file_parts = output_file.split('.')

	_save(single_level, f"{'.'.join(output_file_parts[:-1])}.SingleLevel.{t0:%Y%m%d%H%M}.{output_file_parts[-1]}")
	_save(pressure_levels, f"{'.'.join(output_file_parts[:-1])}.PressureLevels.{t0:%Y%m%d%H%M}.{output_file_parts[-1]}")


@log
def _update_datetime(x):
	return x.assign_coords(time=pd.to_datetime(x.coords['time']))


@log
def _zero_negative_precipitation(x):
	x['total_precipitation_6hr'] = x['total_precipitation_6hr'].where(x['total_precipitation_6hr'] >= 0, 0)
	return x


@log
def _save(x, file):
	output_format = file.split('.')[-1]
	if output_format in ['nc', 'netcdf']:
		x.to_netcdf(file, format='NETCDF4', encoding={v: {'zlib': True, 'complevel': 4} for v in x.data_vars})
	elif output_format == 'zarr':
		x.to_zarr(file, mode='w')
	elif output_format == 'json':
		with open(file, 'w') as w:
			json.dump(x.to_dict(), w, default=str)
	elif output_format in ['txt', 'csv']:
		x.to_dataframe().to_csv(file)


@log
def _metadata(x):
	for r in x.variables:
		if r in _output_metadata['variables']:
			for k, v in _output_metadata['variables'][r].items():
				x[r].attrs[k] = v
	for k, v in _output_metadata['global'].items():
		x.attrs[k] = v
	return x


@log
def _trim(x, levels, fields):
	return x[fields].sel(level=levels).squeeze(['batch'])


@log
def _clip(x, corners):
	return x.where(
		(x.lon >= min([c[0] % 360 for c in corners])) &
		(x.lon <= max([c[0] % 360 for c in corners])) &
		(x.lat >= min([c[1] for c in corners])) &
		(x.lat <= max([c[1] for c in corners])), drop=True)


@log
def _resample(x, downscale, downscale_method):
	lat_min, lat_max = x.lat.values.min(), x.lat.values.max()
	lon_min, lon_max = x.lon.values.min(), x.lon.values.max()
	return x.interp({'lat': np.arange(lat_min, lat_max, downscale), 'lon': np.arange(lon_min, lon_max, downscale)}, downscale_method)


@log
def _split(x):
	splits = {tuple(x[v].dims): [] for v in x.data_vars}
	[splits[tuple(x[v].dims)].append(v) for v in x.data_vars]
	return x[splits[('time', 'lat', 'lon')]], x[splits[('time', 'lat', 'lon', 'level')]]
